#!/usr/bin/env python3
"""Run LibreOffice (soffice) with a font configuration that works headless.

In headless mode LibreOffice resolves fonts through its bundled fontconfig. On
macOS that library has no configuration of its own, so it sees only the fonts
LibreOffice ships: every template font, including system fonts such as Arial or
Helvetica and fonts installed in ~/Library/Fonts, silently falls back to a
substitute. Line heights and page breaks then differ from Writer and from the
reference baselines, often adding whole pages.

``soffice_env()`` fixes this by pointing ``FONTCONFIG_FILE`` at a generated
configuration that lists the macOS font directories, maps Microsoft fonts to
the metric-compatible substitutes LibreOffice bundles, and includes the private
``JobSearch/Templates/fonts.conf`` when present (for template-specific
substitutions). An explicit ``FONTCONFIG_FILE`` in the environment is kept.
Other platforms use their system fontconfig and are left unchanged.

Run as a script, it passes all arguments to soffice with that environment:

    tools/soffice --headless --convert-to pdf --outdir <dir> <file.odt>

Standard library only.
"""
import os
import shutil
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
PRIVATE_FONTS = ROOT / 'JobSearch' / 'Templates' / 'fonts.conf'
MAC_SOFFICE = Path('/Applications/LibreOffice.app/Contents/MacOS/soffice')
MAC_FONT_DIRS = ('/System/Library/Fonts', '/Library/Fonts', '~/Library/Fonts',
                 '/System/Library/AssetsV2')
# Metric-compatible substitutes bundled with LibreOffice.
SUBSTITUTES = (('Calibri', 'Carlito'), ('Cambria', 'Caladea'))


def find_soffice():
    """Return the soffice executable, preferring the macOS application bundle."""
    if MAC_SOFFICE.is_file():
        return str(MAC_SOFFICE)
    found = shutil.which('soffice')
    if found:
        return found
    raise ValueError('LibreOffice (soffice) not found; install it or export the PDF in Writer.')


def fontconfig_text(private=PRIVATE_FONTS):
    """Return the generated fontconfig document."""
    lines = ['<?xml version="1.0"?>',
             '<!DOCTYPE fontconfig SYSTEM "fonts.dtd">',
             '<!-- Generated by CV/Scripts/office.py; do not edit. -->',
             '<fontconfig>']
    lines += [f'  <dir>{d}</dir>' for d in MAC_FONT_DIRS]
    lines.append('  <cachedir>~/.cache/fontconfig</cachedir>')
    for family, substitute in SUBSTITUTES:
        lines.append(f'  <alias binding="same"><family>{family}</family>'
                     f'<prefer><family>{substitute}</family></prefer></alias>')
    # fontconfig resolves relative includes against its own configuration
    # directory, not this file, so the private include must be absolute.
    lines.append(f'  <include ignore_missing="yes">{escape(str(private))}</include>')
    lines.append('</fontconfig>')
    return '\n'.join(lines) + '\n'


def config_path():
    cache = Path(os.environ.get('XDG_CACHE_HOME') or Path.home() / '.cache')
    return cache / 'jobjimmy' / 'fonts.conf'


def write_config(path=None, private=PRIVATE_FONTS):
    """Write the generated configuration if it changed; return its path."""
    path = Path(path) if path else config_path()
    text = fontconfig_text(private)
    if not path.is_file() or path.read_text(encoding='utf-8') != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix('.tmp')
        temporary.write_text(text, encoding='utf-8')
        temporary.replace(path)
    return path


def soffice_env(base=None, platform=None):
    """Return an environment for running soffice headless."""
    env = dict(os.environ if base is None else base)
    if (platform or sys.platform) == 'darwin' and not env.get('FONTCONFIG_FILE'):
        env['FONTCONFIG_FILE'] = str(write_config())
    return env


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    try:
        soffice = find_soffice()
    except ValueError as error:
        print(f'tools/soffice: {error}', file=sys.stderr)
        return 127
    os.execve(soffice, [soffice, *argv], soffice_env())


if __name__ == '__main__':
    sys.exit(main())
